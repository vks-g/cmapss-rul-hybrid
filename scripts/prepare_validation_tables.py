"""Write the report's validation tables (#76) from the #72 and #70 results.

Run from the repository root after notebooks 12 and 13:

    python scripts/prepare_validation_tables.py

Reads the #71 test predictions (recomputing each model's RMSE and bootstrap CI
exactly as notebook 13 does), ``fd001_validation_value_test.json`` and the
FD002/FD004 official test results
(``fd00{2,4}_test_*.json`` and their predictions), and writes three tables to
``reports/phase2/tables/``.
"""

from __future__ import annotations

import json
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from rul.evaluation.validation import bootstrap_ci  # noqa: E402

METRICS = ROOT / "results" / "metrics"
TABLES = ROOT / "reports" / "phase2" / "tables"
CAP = 125
MULTI_REGIME = (  # (subset, model label, result file stem), as chosen in notebook 12
    ("FD002", "LSTM", "fd002_test_lstm_per_regime"),
    ("FD002", "Hybrid A", "fd002_test_hybrid_gated_global"),
    ("FD004", "LSTM", "fd004_test_lstm_per_regime"),
    ("FD004", "Hybrid A", "fd004_test_hybrid_gated_per_regime"),
)
CRITERIA = ("bootstrap_ci_below_zero", "wilcoxon_holm", "lower_seed_variance")
NETWORKS = {"lstm": "LSTM", "tcn": "Temporal CNN", "transformer": "Transformer",
            "hybrid_gated": "Hybrid A (gated)", "hybrid_two_stage": "Hybrid B (two-stage)"}
ML_NAMES = {"xgboost": "XGBoost", "random_forest": "Random Forest", "elastic_net": "Elastic Net"}


def num(x: float, digits: int = 2, sign: bool = False) -> str:
    """Fixed decimals, halves rounded away from zero, minus and plus signs in math mode."""
    q = Decimal(repr(float(x))).quantize(Decimal(1).scaleb(-digits), rounding=ROUND_HALF_UP)
    text = f"{q:+}" if sign else f"{q}"
    return text.replace("+", "$+$").replace("-", "$-$")


def pm(mean: float, sd: float | None) -> str:
    return num(mean) if sd is None or np.isnan(sd) else f"{num(mean)} $\\pm$ {num(sd)}"


def pvalue(p: float) -> str:
    return "$<$0.001" if p < 0.001 else f"{p:.3f}" if p < 0.1 else f"{p:.2f}"


def latex_name(name: str) -> str:
    return name.replace(" (", ", ").replace(")", "")


def model_predictions(metrics: Path = METRICS) -> dict:
    """{(model, target): predictions shaped [seeds, engines]} and the true RUL, as in notebook 13."""
    final = pd.read_csv(metrics / "fd001_final_test_predictions.csv")
    ml = pd.read_csv(metrics / "fd001_ml_capped_test_predictions.csv").set_index("unit").sort_index()
    units = ml.index.to_numpy()
    preds = {}
    for key, name in NETWORKS.items():
        for target in ("cap125", "uncapped"):
            wide = final[(final.model == key) & (final.target == target)].pivot(
                index="seed", columns="unit", values="prediction")
            preds[name, target] = wide[units].to_numpy()
    for variant in ("engineered", "raw"):
        for key, name in ML_NAMES.items():
            for cap, target in (("125", "cap125"), ("none", "uncapped")):
                preds[f"{name} ({variant})", target] = ml[f"{variant}_{key}_cap{cap}"].to_numpy()[None, :]
    return preds, ml["rul"].to_numpy(dtype=float)


def models_table(metrics: Path = METRICS) -> str:
    preds, y = model_predictions(metrics)
    stats = {}
    for (name, target), p in preds.items():
        per_seed = np.sqrt(np.mean((p - y) ** 2, axis=1))
        ci = bootstrap_ci(y, p, "rmse")
        stats[name, target] = {"mean": per_seed.mean(), "sd": per_seed.std(ddof=1) if len(per_seed) > 1 else None,
                               "low": ci["low"], "high": ci["high"], "seeds": len(per_seed),
                               "mae": float(np.abs(p - y).mean(axis=1).mean())}
    order = sorted({n for n, _ in preds}, key=lambda n: stats[n, "cap125"]["mean"])
    rows = []
    for name in order:
        c, u = stats[name, "cap125"], stats[name, "uncapped"]
        rows.append(" & ".join([
            latex_name(name), str(c["seeds"]), pm(c["mean"], c["sd"]), f"[{num(c['low'])}, {num(c['high'])}]",
            num(c["mae"]), pm(u["mean"], u["sd"]),
        ]) + r" \\")
    return "\n".join([
        "% Generated by scripts/prepare_validation_tables.py from the #71 test predictions",
        "% (results/metrics/fd001_final_test_predictions.csv, fd001_ml_capped_test_predictions.csv),",
        "% as in notebooks/phase2/13_validation.ipynb (#72). Do not edit by hand.",
        r"\begin{tabular}{@{}lccccc@{}}",
        r"\hline",
        r"Model & Seeds & RMSE & 95\% CI & MAE & RMSE, uncapped \\",
        r"\hline",
        *rows,
        r"\hline",
        r"\end{tabular}",
        "",
    ])


def paired_table(metrics: Path = METRICS) -> str:
    record = json.loads((metrics / "fd001_validation_value_test.json").read_text())
    rows = []
    for name, (a, b) in record["comparisons"].items():
        v = record["verdicts"][name]
        ev = v["evidence"]
        d = ev["rmse_difference"]
        hybrid = a.startswith("Hybrid")
        branch_has_seeds = ev["rmse_branch"]["std"] is not None
        marks = []
        for c in CRITERIA:
            if c == "lower_seed_variance" and not branch_has_seeds:
                marks.append("n/a")
            else:
                marks.append("yes" if v["criteria"][c] else "no")
        verdict = ("adds value" if v["adds_value"] else "null") if hybrid else (
            "A better" if d["high"] < 0 else "B better" if d["low"] > 0 else "tie")
        rows.append(" & ".join([
            latex_name(a.replace(" (gated)", "").replace(" (two-stage)", "")),
            latex_name(b),
            f"{num(d['difference'], sign=True)} [{num(d['low'], sign=True)}, {num(d['high'], sign=True)}]",
            pvalue(ev["wilcoxon"]["p_holm"]),
            *(marks if hybrid else ["--", "--", "--"]),
            verdict,
        ]) + r" \\")
    return "\n".join([
        "% Generated by scripts/prepare_validation_tables.py from",
        "% results/metrics/fd001_validation_value_test.json (#72). Do not edit by hand.",
        r"\begin{tabular}{@{}llcccccl@{}}",
        r"\hline",
        r"A & B & $\Delta$ [95\% CI] & $p_\mathrm{Holm}$ & (1) & (2) & (3) & Verdict \\",
        r"\hline",
        *rows,
        r"\hline",
        r"\end{tabular}",
        "",
    ])


def multi_regime_rows(metrics: Path = METRICS) -> list[dict]:
    rows = []
    for subset, model, stem in MULTI_REGIME:
        record = json.loads((metrics / f"{stem}.json").read_text())
        pred = pd.read_csv(metrics / f"{stem}_predictions.csv")
        pred["error"] = pred["prediction"] - pred["rul"]
        above = pred["rul"] > CAP

        def rmse(frame):
            return frame.groupby("seed")["error"].apply(lambda e: np.sqrt(np.mean(e**2))).mean()

        rows.append({
            "subset": subset, "model": model, "scaling": record["scaling"],
            "rmse": record["summary"]["rmse"]["mean"], "sd": record["summary"]["rmse"]["std"],
            "nasa": record["summary"]["nasa_score"]["mean"],
            "below": rmse(pred[~above]), "above": rmse(pred[above]),
            "share": above.groupby(pred["seed"]).mean().mean(),
        })
    return rows


def multi_regime_table(metrics: Path = METRICS) -> str:
    rows = [" & ".join([
        r["subset"], r["model"], r["scaling"], pm(r["rmse"], r["sd"]), f"{r['nasa']:,.0f}".replace(",", "{,}"),
        num(r["below"]), num(r["above"]), f"{round(100 * r['share'])}\\%",
    ]) + r" \\" for r in multi_regime_rows(metrics)]
    return "\n".join([
        "% Generated by scripts/prepare_validation_tables.py from",
        "% results/metrics/fd00{2,4}_test_*.json and predictions (#70). Do not edit by hand.",
        r"\begin{tabular}{@{}lllccccc@{}}",
        r"\hline",
        r"Subset & Model & Scaling & RMSE & NASA & RMSE, $y\leq125$ & RMSE, $y>125$ & $y>125$ \\",
        r"\hline",
        *rows,
        r"\hline",
        r"\end{tabular}",
        "",
    ])


BUILDERS = {
    "validation_models.tex": models_table,
    "validation_paired.tex": paired_table,
    "multi_regime_test.tex": multi_regime_table,
}


def main() -> None:
    for name, build in BUILDERS.items():
        (TABLES / name).write_text(build())
        print(f"wrote {(TABLES / name).relative_to(ROOT)}")


if __name__ == "__main__":
    main()
