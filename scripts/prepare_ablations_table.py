"""Write the report's ablation table (#75) from the #69 result CSVs.

Run from the repository root after notebooks/phase2/11_ablations.ipynb:

    python scripts/prepare_ablations_table.py

Reads ``results/metrics/fd001_ablations{,_paired,_seeds}.csv`` and writes
``reports/phase2/tables/ablations.tex``. Rows in the top block use the three
seeds of the window and branch groups; the bottom block uses seed 42.
"""

from __future__ import annotations

from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "results" / "metrics"
OUT = ROOT / "reports" / "phase2" / "tables" / "ablations.tex"
BASE = "branch_gated"
STAGES = ("early", "mid", "late")
MULTI_SEED = {
    "window_15": "Window 15",
    "window_60": "Window 60",
    "window_90": "Window 90",
    "branch_sequence": "Sequence branch only",
    "branch_features": "Feature branch only",
    "branch_concat": "Concatenation, no gate",
}
SINGLE_SEED = {
    "cap_none": "No cap",
    "cap_100": "Cap 100",
    "cap_150": "Cap 150",
    "features_no_age": "Features: no age",
    "features_current_only": "Features: current only",
    "features_rolling_only": "Features: rolling only",
    "cycle_on": "Cycle index input",
    "loss_asymmetric": "Asymmetric loss",
}


def num(x: float, sign: bool = False) -> str:
    """Two decimals, halves rounded away from zero, minus and plus signs in math mode."""
    q = Decimal(repr(float(x))).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    text = f"{q:+}" if sign else f"{q}"
    return text.replace("+", "$+$").replace("-", "$-$")


def pvalue(p: float) -> str:
    return "$<$0.001" if p < 0.001 else f"{p:.3f}" if p < 0.1 else f"{p:.2f}"


def build(metrics: Path = METRICS) -> str:
    summary = pd.read_csv(metrics / "fd001_ablations.csv").set_index("variant")
    paired = pd.read_csv(metrics / "fd001_ablations_paired.csv").set_index("variant")
    seeds = pd.read_csv(metrics / "fd001_ablations_seeds.csv").set_index("variant")

    def stage_cells(variant: str, multi: bool) -> list[str]:
        if multi:
            return [num(seeds.loc[variant, f"{s} mean"]) for s in STAGES]
        return [num(summary.loc[variant, f"{s}_rmse"]) for s in STAGES]

    def block(labels: dict[str, str], n_seeds: int) -> list[str]:
        multi = n_seeds > 1
        base_rmse = paired.query("seeds == @n_seeds")["base RMSE"].iloc[0]
        rows = [[r"\textbf{Base (Hybrid A)}", str(n_seeds), num(base_rmse), "--", "--",
                 *stage_cells(BASE, multi)]]
        for variant, label in labels.items():
            r = paired.loc[variant]
            ci = f"{num(r['difference'], True)} [{num(r['CI low'], True)}, {num(r['CI high'], True)}]"
            rows.append([label, str(n_seeds), num(r["variant RMSE"]), ci, pvalue(r["Holm p"]),
                         *stage_cells(variant, multi)])
        return [" & ".join(cells) + r" \\" for cells in rows]

    return "\n".join([
        "% Generated by scripts/prepare_ablations_table.py from",
        "% results/metrics/fd001_ablations{,_paired,_seeds}.csv (#69). Do not edit by hand.",
        r"\begin{tabular}{@{}lccccccc@{}}",
        r"\hline",
        r"Variant & Seeds & RMSE & $\Delta$ [95\% CI] & $p_\mathrm{Holm}$ & Early & Mid & Late \\",
        r"\hline",
        *block(MULTI_SEED, 3),
        r"\hline",
        *block(SINGLE_SEED, 1),
        r"\hline",
        r"\end{tabular}",
        "",
    ])


def main() -> None:
    OUT.write_text(build())
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
