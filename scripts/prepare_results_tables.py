"""Write the report tables for the hybrid and results sections (#81).

Run from the repository root after notebooks 09, 13 and 15:

    python scripts/prepare_results_tables.py

Writes two tables to ``reports/phase2/tables/``:

* ``hybrid_value_cv.tex``: the cross-validated value test of the hybrid study
  (#68), from ``fd001_hybrid_value_test.json``;
* ``final_results.tex``: every model trained with the cap, with its
  cross-validated selection RMSE next to its official test scores (#71), the
  test scores recomputed from the saved per-engine predictions.

Number formatting and the test predictions are shared with
``scripts/prepare_validation_tables.py``, so both scripts print a model's
scores the same way.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
from prepare_validation_tables import (  # noqa: E402
    CRITERIA,
    ML_NAMES,
    NETWORKS,
    latex_name,
    model_predictions,
    num,
    pm,
    pvalue,
)
from rul.evaluation.metrics import evaluate  # noqa: E402

METRICS = ROOT / "results" / "metrics"
TABLES = ROOT / "reports" / "phase2" / "tables"
STAGES = ("late", "mid", "early")
HYBRID_ROWS = (  # (key in fd001_hybrid_value_test.json, label in the table)
    ("gated fusion (Hybrid A)", "Hybrid A, gated"),
    ("concatenation", "Concatenation"),
    ("two-stage (Hybrid B)", "Hybrid B, two-stage"),
)
BRANCH_LABELS = {"sequence only (LSTM)": "LSTM", "XGBoost on features": "XGBoost, features"}


def hybrid_value_table(metrics: Path = METRICS) -> str:
    record = json.loads((metrics / "fd001_hybrid_value_test.json").read_text())
    rows = []
    for key, label in HYBRID_ROWS:
        v = record["verdicts"][key]
        ev = v["evidence"]
        d = ev["rmse_difference"]
        passed = [c for c in CRITERIA if v["criteria"][c]]
        verdict = f"passes ({', '.join(str(CRITERIA.index(c) + 1) for c in passed)})" if passed else "null"
        rows.append(" & ".join([
            label,
            BRANCH_LABELS[record["best_branch"][key]],
            pm(ev["rmse_hybrid"]["mean"], ev["rmse_hybrid"]["std"]),
            pm(ev["rmse_branch"]["mean"], ev["rmse_branch"]["std"]),
            f"{num(d['difference'], sign=True)} [{num(d['low'], sign=True)}, {num(d['high'], sign=True)}]",
            pvalue(ev["wilcoxon"]["p_holm"]),
            *("yes" if v["criteria"][c] else "no" for c in CRITERIA),
            verdict,
        ]) + r" \\")
    return "\n".join([
        "% Generated by scripts/prepare_results_tables.py from",
        "% results/metrics/fd001_hybrid_value_test.json (#68). Do not edit by hand.",
        r"\begin{tabular}{@{}llcccccccl@{}}",
        r"\hline",
        r"Hybrid & Best branch & Hybrid & Branch & $\Delta$ [95\% CI] & $p_\mathrm{Holm}$"
        r" & (1) & (2) & (3) & Verdict \\",
        r"\hline",
        *rows,
        r"\hline",
        r"\end{tabular}",
        "",
    ])


def cv_selection_rmse(metrics: Path = METRICS) -> dict[str, float]:
    """Cross-validated selection RMSE (seed 42, mean over the 3 folds) of every model trained with the cap."""
    scores = {}
    for key, name in NETWORKS.items():
        record = json.loads((metrics / f"fd001_cv_{key}.json").read_text())
        scores[name] = record["summary"]["selection_rmse"]["mean"]
    for chosen in json.loads((metrics / "fd001_ml_capped_cv.json").read_text())["chosen"]:
        if chosen["cap"] == "125":
            scores[f"{ML_NAMES[chosen['model']]} ({chosen['variant']})"] = chosen["selection_rmse"]["mean"]
    return scores


def test_scores(metrics: Path = METRICS) -> dict[str, dict]:
    """Official test scores of every capped model: mean and s.d. over seeds, as in notebook 15."""
    preds, y = model_predictions(metrics)
    scores = {}
    for (name, target), p in preds.items():
        if target != "cap125":
            continue
        runs = [evaluate(y, seed) for seed in p]

        def stat(get):
            values = np.array([get(r) for r in runs])
            return values.mean(), values.std(ddof=1) if len(values) > 1 else None

        scores[name] = {
            "rmse": stat(lambda r: r["rmse"]),
            "nasa": stat(lambda r: r["nasa_score"]),
            **{s: stat(lambda r, s=s: r["by_stage"][s]["rmse"]) for s in STAGES},
        }
    return scores


def final_results_table(metrics: Path = METRICS) -> str:
    cv = cv_selection_rmse(metrics)
    test = test_scores(metrics)
    rows = []
    for name in sorted(test, key=lambda n: test[n]["rmse"][0]):
        t = test[name]
        nasa_mean, nasa_sd = t["nasa"]
        nasa = f"{nasa_mean:,.0f}".replace(",", "{,}") + (f" $\\pm$ {nasa_sd:.0f}" if nasa_sd is not None else "")
        rows.append(" & ".join([
            latex_name(name), num(cv[name]), pm(*t["rmse"]), nasa, *(num(t[s][0]) for s in STAGES),
        ]) + r" \\")
    return "\n".join([
        "% Generated by scripts/prepare_results_tables.py from the cross-validation results",
        "% (fd001_cv_*.json, fd001_ml_capped_cv.json) and the #71 test predictions. Do not edit by hand.",
        r"\begin{tabular}{@{}lcccccc@{}}",
        r"\hline",
        r" & CV & \multicolumn{5}{c}{Official test} \\",
        r"Model & $\mathrm{RMSE}_{\leq130}$ & RMSE & NASA score & Late & Mid & Early \\",
        r"\hline",
        *rows,
        r"\hline",
        r"\end{tabular}",
        "",
    ])


BUILDERS = {
    "hybrid_value_cv.tex": hybrid_value_table,
    "final_results.tex": final_results_table,
}


def main() -> None:
    for name, build in BUILDERS.items():
        (TABLES / name).write_text(build())
        print(f"wrote {(TABLES / name).relative_to(ROOT)}")


if __name__ == "__main__":
    main()
